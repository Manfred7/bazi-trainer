# Эмблемы званий через Codex (встроенная генерация изображений), как scripts/gen-images.ps1 в «Паре вкуса».
# Уже нарисованные <id>.png пропускаются — скрипт можно перезапускать.
#   pwsh scripts/gen-ranks.ps1 -Out <папка для png>
# Потом: python scripts/build-ranks.py <папка с png>  →  public/ranks/<id>.webp
param([Parameter(Mandatory)] [string]$Out)

$ranks = [ordered]@{
  novice      = 'одна капля чёрной туши на чистом листе рисовой бумаги и лежащая рядом тонкая кисть'
  amateur     = 'кисть, проводящая одну горизонтальную черту тушью по бумаге'
  adept       = 'тушечница с растёртой тушью, кисть на подставке и брусок туши'
  master      = 'квадратная печать из камня и оттиск киноварью на бумаге рядом, без читаемых знаков'
  magister    = 'развёрнутый свиток с каллиграфией, кисть и красная печать, бронзовый компас лопань на заднем плане'
  grandmaster = 'золотой дракон, обвивающий круг из шестидесяти маленьких красных печатей'
}
$style = 'китайская живопись тушью гохуа с акцентами киновари и золота, тёплые бумажные тона, единый стиль для всей серии, как набор наград-медальонов'

New-Item -ItemType Directory -Force $Out | Out-Null
$todo = @($ranks.Keys | Where-Object { -not (Test-Path (Join-Path $Out "$_.png")) })
Write-Host "Нарисовать: $($todo.Count) из $($ranks.Count)"
if (-not $todo.Count) { return }

$list = ($todo | ForEach-Object { "$_ — $($ranks[$_])" }) -join "`n"
$prompt = @"
Сгенерируй инструментом генерации изображений по одной картинке на каждое звание из списка ниже (формат «id — что нарисовать»).
Это эмблемы званий в приложении-тренажёре письма китайских знаков, от новичка к гранд мастеру: чем выше звание, тем богаче и торжественнее эмблема.
Общий стиль для ВСЕХ картинок, одинаковый: $style
Требования к каждой: квадрат, круглый медальон по центру, занимает примерно 90% кадра, сюжет внутри медальона; фон вокруг медальона однотонный светло-кремовый (#F5F0E6); без текста, без букв, без иероглифов и надписей, без рамки вокруг кадра.
Каждую сохрани (скопируй сгенерированный файл) в папку $Out с именем <id>.png. Ничего кроме этого не делай. В конце перечисли сохранённые файлы.

$list
"@
Set-Location $Out
codex exec --skip-git-repo-check -s workspace-write $prompt *> (Join-Path $Out '_log.txt')
$left = @($ranks.Keys | Where-Object { -not (Test-Path (Join-Path $Out "$_.png")) })
Write-Host "Готово. Не нарисовано: $($left.Count) $($left -join ', ')"
